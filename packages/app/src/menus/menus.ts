/**
 * The full menu tree — spec 01 §3.
 *
 * Every item Photoshop has (minus the deliberate non-goals listed in the spec) appears here,
 * in the same menu, in the same order, with the same shortcut. Items whose command does not
 * exist yet are present but disabled, which is what makes the M1 exit criterion testable: a
 * Photoshop user can go looking for anything and find it where they expect.
 *
 * `cmd` is the command id the command bus will dispatch. `done: true` marks the ones wired up
 * today; everything else renders greyed.
 */

import { FILTER_BY_ID } from '@umbra/engine';

/** A Filter-menu leaf, enabled exactly when the filter registry implements it. */
const filterItem = (label: string, cmd: string): MenuNode => (FILTER_BY_ID.has(cmd) ? { label, cmd, done: true } : { label, cmd });

export interface MenuNode {
  /** Divider line; no other field applies. */
  separator?: true;
  label?: string;
  /** Command id dispatched on click. */
  cmd?: string;
  /** Display shortcut, e.g. "Ctrl+Shift+N". */
  shortcut?: string;
  /** Submenu. */
  items?: MenuNode[];
  /** Implemented and clickable. */
  done?: true;
  /** Shows a check mark; the app supplies live state by id. */
  checkable?: true;
  /** Opens a dialog (renders the "…" affordance is already in the label). */
  dialog?: true;
}

export interface MenuDef {
  label: string;
  items: MenuNode[];
}

