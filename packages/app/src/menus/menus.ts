/** Flattened command index, for the keymap and the command palette. */
export interface CommandInfo {
  cmd: string;
  label: string;
  path: string[];
  shortcut?: string;
  done: boolean;
}

export const COMMANDS: CommandInfo[] = (() => {
  const out: CommandInfo[] = [];
  const visit = (nodes: MenuNode[], path: string[]) => {
    for (const n of nodes) {
      if (n.separator) continue;
      const here = [...path, n.label ?? ''];
      if (n.items) visit(n.items, here);
      else if (n.cmd) out.push({ cmd: n.cmd, label: n.label ?? n.cmd, path, shortcut: n.shortcut, done: !!n.done });
    }
  };
  for (const m of MENUS) visit(m.items, [m.label]);
  return out;
})();

export const COMMAND_BY_ID = new Map(COMMANDS.map((c) => [c.cmd, c]));
